import type { NextConfig } from "next";
import { withWorkflow } from "workflow/next";
import { IFRAME_EMBED_ENABLED, getAllowedAncestorOrigins } from "./src/lib/iframe";
import { INGEST_PATH_PREFIX, posthogUpstreams } from "./src/lib/posthog-proxy";

// Same-origin reverse proxy for posthog-js (`api_host: '/ingest'`). Resolved by
// the platform's edge routing layer, so no function is invoked per captured
// event. Returns no rewrites when PostHog isn't configured.
const posthog = posthogUpstreams(process.env.NEXT_PUBLIC_POSTHOG_HOST);

// `frame-ancestors` controls who may embed this app in an <iframe>. When
// embedding is enabled we permit the launcher origins (plus 'self'); otherwise
// we lock framing down to same-origin as clickjacking hardening. We rely on
// this CSP directive rather than `X-Frame-Options` (which we never send) —
// `frame-ancestors` is the modern mechanism and overrides X-Frame-Options.
const frameAncestors = IFRAME_EMBED_ENABLED
  ? ["'self'", ...getAllowedAncestorOrigins()].join(" ")
  : "'self'";

const nextConfig: NextConfig = {
  typescript: { ignoreBuildErrors: true },
  // Apply `frame-ancestors` to every route so page and asset responses alike
  // are (dis)allowed from framing consistently.
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: [
          {
            key: "Content-Security-Policy",
            value: `frame-ancestors ${frameAncestors};`,
          },
        ],
      },
    ];
  },
  // posthog-js addresses its endpoints with trailing slashes (`/e/`,
  // `/flags/?v=2`). Next's default trailing-slash normalization would answer
  // those with a 308 before the rewrite runs, costing a round-trip on every
  // captured event. Site-wide setting: `/some-page/` no longer redirects to
  // `/some-page` either — safe here because every in-app link is generated by
  // `next/link` without a trailing slash.
  skipTrailingSlashRedirect: true,
  // PostHog serves ingestion and static assets from two different hosts, so
  // `/ingest/static/*` has to be matched before the catch-all. `src/proxy.ts`
  // strips cookies/authorization off these requests before they leave our
  // origin — see `CREDENTIAL_HEADERS` in `src/lib/posthog-proxy.ts`.
  async rewrites() {
    if (!posthog) return [];
    return [
      {
        source: `${INGEST_PATH_PREFIX}/static/:path*`,
        destination: `${posthog.assetHost}/static/:path*`,
      },
      {
        source: `${INGEST_PATH_PREFIX}/:path*`,
        destination: `${posthog.apiHost}/:path*`,
      },
    ];
  },
  // `output: "standalone"` is for self-host / Docker-style deploys.
  // Disable it when:
  // - Playwright e2e sets NEXT_DISABLE_STANDALONE (next start can't serve standalone)
  // - Vercel (VERCEL=1): Next 16.3+ Turbopack skips next-server.js.nft.json when
  //   build adapters run (e.g. withWorkflow), so writeStandaloneDirectory fails
  //   with ENOENT. Vercel ignores the standalone folder anyway.
  output:
    process.env.NEXT_DISABLE_STANDALONE || process.env.VERCEL
      ? undefined
      : "standalone",
  reactStrictMode: true,
  images: {
    unoptimized: true,
  },
  // `@react-pdf/renderer` pulls in fontkit and a base64-inlined yoga-layout
  // wasm module. Bundling those through Turbopack breaks the wasm init, so the
  // package is loaded from node_modules at runtime instead.
  //
  // `mem0ai` is server-only and reaches ~40 optional vector-store / LLM / graph
  // SDKs through dynamic `import()`s guarded by `loadPeer`. Bundling it makes
  // the compiler try to resolve every one of those at build time and fail on
  // the ~39 we do not install (zeroentropy, oracledb, weaviate-client, ...).
  // Kept external so those imports stay runtime-lazy, which is what mem0 already
  // assumes. See src/lib/memory/.
  serverExternalPackages: ["@resvg/resvg-js", "@react-pdf/renderer", "mem0ai"],
  // The research-summary PDF reads Inter and Source Serif 4 out of
  // `public/fonts` with a plain `fs.readFileSync`, which the tracer cannot
  // see. Next happens to trace all
  // of `public/` into every function today, so this is belt-and-braces rather
  // than load-bearing — it pins the dependency explicitly so the fonts cannot
  // quietly stop shipping. Without them the renderer falls back to the built-in
  // Helvetica and Times, and every non-Latin-1 character disappears (see
  // `src/lib/pdf/fonts.ts`).
  //
  // The workspace PowerPoint template's brand images (logo, page tab) are read
  // the same way from `src/lib/pptx/templates/assets`, outside `public/` so
  // they are not downloadable — which means nothing traces them unless listed
  // here. The Pipeline "Present" download is the route that reads them.
  outputFileTracingIncludes: {
    "/api/**": ["./public/fonts/**", "./src/lib/pptx/templates/assets/**"],
  },
};

export default withWorkflow(nextConfig);
