"use client";

import { useEffect, useState } from "react";
import { Zap, Loader2, Check, AlertCircle, ArrowUpRight } from "lucide-react";
import { toast } from "sonner";

import { Button } from "@/components/ui/button";
import { cn } from "@/lib/utils";
import { apiRequest } from "@/lib/api/client";
import { EffortSelector } from "@/components/chat/EffortSelector";
import { WorkspaceLink } from "@/components/WorkspaceLink";
import { useLayoutControl } from "@/components/layout/LayoutControlContext";
import type { EffortChoice } from "@/lib/agents/analysis";

const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Deep-link to the queued row when we have its id, otherwise to the queue
 * itself. The `/tasks/<id>` route validates the UUID server-side and 404s on
 * anything else, so a non-UUID id falls back rather than sending the user to a
 * not-found page — and the label follows the destination so the button never
 * promises a task it isn't opening.
 */
function workforceLink(queueId: string | null): { href: string; label: string } {
  return queueId && UUID_RE.test(queueId)
    ? { href: `/ai-workforce/tasks/${queueId}`, label: "View task in AI Workspace" }
    : { href: "/ai-workforce", label: "Open AI Workspace" };
}

export interface WorkforceHandoffPayload {
  handoff_id?: string;
  title: string;
  rationale: string;
  instruction: string;
  agent_name: string;
  // Resolved company IDs forwarded to /api/workforce-queue. The server uses
  // these to re-validate that no targeted company is dropped before enqueue.
  // Optional for backward compat with marker payloads written before the
  // dropped-company guard shipped.
  company_ids?: string[];
}

interface WorkforceHandoffCardProps {
  payload: WorkforceHandoffPayload;
  onJustAnswerHere: () => void;
  className?: string;
}

type Status = "idle" | "submitting" | "assigned" | "declined";

export function WorkforceHandoffCard({
  payload,
  onJustAnswerHere,
  className,
}: WorkforceHandoffCardProps) {
  const handoffId = payload.handoff_id;
  const [status, setStatus] = useState<Status>("idle");
  const [queueId, setQueueId] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [effort, setEffort] = useState<EffortChoice>("medium");
  // The copilot pane may be full-screen over the console; navigating behind it
  // would look like the click did nothing (same rationale as CompanyChip).
  const { revealConsole } = useLayoutControl();

  // On mount, check whether this handoff was already assigned in a previous
  // session. The stable key is payload.handoff_id (UUID generated by the
  // server-side tool and embedded in the marker JSON). It survives chat
  // reload because the JSON is part of the persisted tool output content —
  // unlike the AI SDK's toolCallId, which is regenerated on each reload.
  useEffect(() => {
    if (!handoffId) return;
    let cancelled = false;
    (async () => {
      try {
        const body = await apiRequest<{ item?: { id?: string } | null }>(
          `/api/workforce-queue?tool_call_id=${encodeURIComponent(handoffId)}`,
        );
        if (cancelled) return;
        if (body.item?.id) {
          setQueueId(body.item.id);
          setStatus("assigned");
        }
      } catch {
        // Best-effort lookup — silently fall through to idle state.
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [handoffId]);

  const handleAssign = async () => {
    setStatus("submitting");
    setError(null);
    try {
      const body = await apiRequest<{ id?: string }>("/api/workforce-queue", {
        method: "POST",
        body: JSON.stringify({
          agent_name: payload.agent_name,
          title: payload.title,
          instruction: payload.instruction,
          tool_call_id: handoffId,
          company_ids: payload.company_ids ?? [],
          effort,
        }),
      });
      setQueueId(body?.id ?? null);
      setStatus("assigned");
      toast.success("Assigned to Workforce");
    } catch (e) {
      const message = e instanceof Error ? e.message : "Failed to assign";
      setError(message);
      setStatus("idle");
      toast.error("Failed to assign to Workforce", { description: message });
    }
  };

  const handleDecline = () => {
    setStatus("declined");
    onJustAnswerHere();
  };

  return (
    <div
      data-testid="workforce-handoff-card"
      className={cn(
        "w-full rounded-2xl border border-amber-300/70 bg-gradient-to-br from-amber-50 via-orange-50 to-amber-50 dark:from-amber-950/30 dark:via-orange-950/20 dark:to-amber-950/30 shadow-sm overflow-hidden",
        className,
      )}
    >
      <div className="h-1 bg-gradient-to-r from-amber-400 via-orange-400 to-blue-500" />
      <div className="p-5">
        <div className="inline-flex items-center gap-1.5 text-[11px] font-bold tracking-wider uppercase text-amber-700 dark:text-amber-400 mb-2">
          <Zap className="h-3.5 w-3.5" />
          Send to Workforce?
        </div>
        <h3 className="text-base font-semibold text-foreground mb-1.5">
          {payload.title}
        </h3>
        <p className="text-sm text-muted-foreground leading-relaxed mb-4">
          {payload.rationale}
        </p>

        <div className="rounded-lg border border-amber-200/60 dark:border-amber-900/40 bg-background/60 p-3.5 mb-4">
          <div className="text-[11px] font-bold tracking-wider uppercase text-muted-foreground mb-1.5">
            I&apos;ll instruct the Workforce to:
          </div>
          <p className="text-sm text-foreground leading-relaxed">
            {payload.instruction}
          </p>
        </div>

        {status === "assigned" ? (
          <div className="flex flex-col gap-3">
            <div className="flex items-center gap-2 text-sm text-emerald-700 dark:text-emerald-400">
              <Check className="h-4 w-4" />
              <span className="font-medium">Assigned to Workforce.</span>
              {queueId && (
                <span className="text-xs font-mono text-muted-foreground">
                  #{queueId.slice(0, 8)}
                </span>
              )}
            </div>
            <Button
              asChild
              variant="outline"
              data-testid="workforce-handoff-view-button"
              className="w-full"
            >
              <WorkspaceLink
                href={workforceLink(queueId).href}
                onClick={revealConsole}
              >
                {workforceLink(queueId).label}
                <ArrowUpRight className="h-4 w-4 ml-1.5" />
              </WorkspaceLink>
            </Button>
          </div>
        ) : status === "declined" ? (
          <div className="flex items-center gap-2 text-sm text-muted-foreground">
            <AlertCircle className="h-4 w-4" />
            <span>Continuing in chat — ask a follow-up to proceed.</span>
          </div>
        ) : (
          <div className="flex flex-col gap-2 w-full">
            <div className="flex items-center justify-between text-xs text-muted-foreground mb-1">
              <span>Effort</span>
              <EffortSelector value={effort} onChange={(v) => { if (v !== 'auto') setEffort(v); }} hideAuto />
            </div>
            <Button
              data-testid="workforce-handoff-assign-button"
              onClick={handleAssign}
              disabled={status === "submitting"}
              className="w-full bg-gradient-to-r from-blue-600 to-blue-600 hover:from-blue-700 hover:to-blue-700 text-white"
            >
              {status === "submitting" ? (
                <>
                  <Loader2 className="h-4 w-4 mr-1.5 animate-spin" />
                  Assigning…
                </>
              ) : (
                "Assign to Workforce"
              )}
            </Button>
            <Button
              data-testid="workforce-handoff-decline-button"
              variant="outline"
              onClick={handleDecline}
              disabled={status === "submitting"}
              className="w-full"
            >
              Just answer here
            </Button>
            {error && (
              <span className="text-xs text-destructive">{error}</span>
            )}
          </div>
        )}
      </div>
    </div>
  );
}
