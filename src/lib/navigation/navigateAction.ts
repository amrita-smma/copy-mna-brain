/**
 * The wire format between the copilot's `navigate_page` tool and the chat UI.
 *
 * Kept in its own dependency-free module because both ends need it: the tool
 * (server, LangChain) writes the marker, and the chat UI (client) reads it.
 * Importing the tool itself from a client component would drag LangChain,
 * `node:crypto` and the DB container into the browser bundle.
 */

import { isConsoleTabPath } from './consoleTabs';

/** HTML comment marker wrapping the JSON payload in the tool's output. */
export const NAVIGATE_PAGE_MARKER = 'NAVIGATE_PAGE_JSON';

export interface NavigatePagePayload {
  /**
   * Stable per-call id. The client keeps a baseline of the ids already present
   * when a chat loads and only navigates for ids that appear *after* it, so
   * re-opening an old chat from history replays nothing. Generated by the tool
   * (rather than read off the AI SDK's toolCallId) because that id differs
   * between the live stream and a reload from the DB — this one is persisted
   * inside the tool's own output.
   */
  nav_id: string;
  slug: string;
  /** Workspace-relative path; the client prefixes the active workspace slug. */
  path: string;
  label: string;
  reason: string;
}

/** Matches every marker in a string. Build a fresh one per use — it is global. */
export function navigateMarkerPattern(): RegExp {
  return new RegExp(`<!--\\s*${NAVIGATE_PAGE_MARKER}:(.*?)-->`, 'gs');
}

/**
 * Every well-formed payload embedded in a tool output, in order. Malformed or
 * incomplete markers are skipped rather than thrown — a half-streamed marker
 * must not break the message it's attached to.
 *
 * `path` is re-checked against the tab registry rather than trusted. The tool
 * only ever emits a console-tab path, but this value is read back out of
 * persisted chat history and handed to `router.push`, so a corrupted or
 * tampered row must not be able to steer navigation somewhere arbitrary.
 */
export function parseNavigatePayloads(content: string): NavigatePagePayload[] {
  if (!content.includes(NAVIGATE_PAGE_MARKER)) return [];
  const found: NavigatePagePayload[] = [];
  for (const match of content.matchAll(navigateMarkerPattern())) {
    try {
      const payload = JSON.parse(match[1]!.trim()) as NavigatePagePayload;
      if (!payload?.nav_id || !payload?.path || !payload?.label) continue;
      if (!isConsoleTabPath(payload.path)) continue;
      found.push(payload);
    } catch {
      // Ignore — an unparseable marker simply doesn't navigate.
    }
  }
  return found;
}

/**
 * Decides what to do with the navigations visible in a transcript.
 *
 * This is the whole replay-suppression rule, kept pure so it can be tested
 * without a DOM. The problem it solves: a `navigate_page` marker lives in the
 * *persisted* tool output, so it reappears every time the transcript renders —
 * on every re-render, and again whenever the user opens that chat from history.
 * Acting on sight would teleport someone who merely scrolled back through an old
 * conversation.
 *
 * So the first time we see a given chat's messages, everything in them is
 * history: absorb the ids, navigate nowhere. From then on, any id we haven't
 * absorbed arrived live and is worth acting on.
 *
 * Only the newest pending navigation is returned. If one turn somehow emitted
 * several, the last is where the user would have ended up anyway, and pushing
 * the intermediate ones would just stack junk onto the history stack.
 */
export function resolveNavigationAction({
  navigations,
  handled,
  isFirstViewOfChat,
  isLiveTurn,
}: {
  /** Every payload currently visible in the transcript, in order. */
  navigations: NavigatePagePayload[];
  /** Ids already absorbed or acted on. */
  handled: ReadonlySet<string>;
  /**
   * True when these messages are the ones this chat arrived with, rather than
   * something that streamed in while the user was watching.
   */
  isFirstViewOfChat: boolean;
  /**
   * True while the copilot is actively producing this turn (`submitted` /
   * `streaming`). History fetches and the in-flight poll both land while status
   * is `ready`; treating those as live would auto-navigate when an old chat's
   * last tool result arrives a moment after load.
   */
  isLiveTurn: boolean;
}): { absorb: string[]; navigateTo: NavigatePagePayload | null } {
  if (isFirstViewOfChat) {
    return { absorb: navigations.map((nav) => nav.nav_id), navigateTo: null };
  }
  const pending = navigations.filter((nav) => !handled.has(nav.nav_id));
  const absorb = pending.map((nav) => nav.nav_id);
  if (!isLiveTurn || pending.length === 0) {
    return { absorb, navigateTo: null };
  }
  return { absorb, navigateTo: pending[pending.length - 1]! };
}

/** Strips every marker so the raw JSON never reaches the rendered transcript. */
export function stripNavigateMarkers(content: string): string {
  return content.replace(
    new RegExp(`\\n*<!--\\s*${NAVIGATE_PAGE_MARKER}:.*?-->`, 'gs'),
    '',
  );
}
